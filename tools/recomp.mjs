// Generates C for every traced block of each version set up in local.json:
//   generated/<id>/recomp_00.c .. recomp_15.c  - block functions plus a per-file table
//   generated/<id>/version.c                  - the version's tables and hook addresses
//   generated/versions.c                      - the versions built (all of config/versions.json,
//                                               NULL for the ones not set up)
// The file counts are fixed so the build system knows the outputs in advance.
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, VERSIONS, loadRoms } from './lib/rom.mjs';
import { trace } from './lib/trace.mjs';
import { loadExtraEntries } from './lib/inputs.mjs';
import { genBlock, usePatches } from './lib/codegen.mjs';
import { configFor } from './lib/versions.mjs';

export const CHUNKS = 16;

// Only rewrite files whose content changed, so the C build stays incremental.
const writeIfChanged = (path, text) => {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return;
  writeFileSync(path, text);
};
const header = '/* Generated by tools/recomp.mjs from the user\'s ROM. Do not edit or distribute. */\n#include "recomp_rt.h"\n\n';
const hex = (s) => `0x${s}`;
const cstr = (s) => JSON.stringify(s).replace(/[\u0080-￿]/g, (c) =>
  [...Buffer.from(c, 'utf8')].map((b) => `\\x${b.toString(16)}`).join('') + '""');
const REGION = { us: 'REGION_US', eu: 'REGION_EU', jp: 'REGION_JP' };

const built = new Set();
for (const { version, rom } of loadRoms()) {
  const { addresses, patches } = configFor(version.id);
  usePatches(patches);
  const t = trace(rom, loadExtraEntries(version.id));
  const parts = t.blocks.flatMap((b) => genBlock(rom, b));
  const id = version.id, outDir = join(ROOT, 'generated', id);
  mkdirSync(outDir, { recursive: true });

  const per = Math.ceil(parts.length / CHUNKS);
  for (let c = 0; c < CHUNKS; c++) {
    const mine = parts.slice(c * per, (c + 1) * per);
    const body = mine.map((p) => p.code).join('\n');
    const table = mine.flatMap((p) => p.entries.map((pc) => `    { 0x${pc.toString(16).toUpperCase()}, ${p.name} },`)).join('\n');
    writeIfChanged(join(outDir, `recomp_${String(c).padStart(2, '0')}.c`), header + body +
      `\nconst RecompEntry recomp_table_${id}_${String(c).padStart(2, '0')}[] = {\n${table}\n    { 0, 0 }\n};\n`);
  }
  const chunks = [...Array(CHUNKS).keys()].map((c) => `recomp_table_${id}_${String(c).padStart(2, '0')}`);
  writeIfChanged(join(outDir, 'version.c'), header + '#include "game.h"\n\n' +
    chunks.map((n) => `extern const RecompEntry ${n}[];`).join('\n') +
    `\n\nstatic const RecompEntry *const tables[] = {\n${chunks.map((n) => `    ${n},`).join('\n')}\n    0\n};\n\n` +
    `const GameVersion game_version_${id} = {\n` +
    `    .id = "${id}", .name = ${cstr(version.name)}, .language = ${cstr(version.language)},\n` +
    `    .title = ${cstr(version.title)},\n` +
    `    .sha1 = "${version.sha1}", .region = ${REGION[version.region]}, .tables = tables,\n` +
    `    .row_draw = 0x${addresses.row_draw},\n` +
    `};\n`);
  built.add(id);
  console.log(`${version.name}: recompiled ${parts.length} block functions from ${t.blocks.length} blocks`);
}

// Every version has an entry, so the build's file list does not depend on which were set up;
// a version not set up gets an empty one (and is NULL in the list).
for (const v of VERSIONS) {
  if (built.has(v.id)) continue;
  const outDir = join(ROOT, 'generated', v.id);
  mkdirSync(outDir, { recursive: true });
  for (let c = 0; c < CHUNKS; c++) writeIfChanged(join(outDir, `recomp_${String(c).padStart(2, '0')}.c`), header + '/* This version is not set up. */\n');
  writeIfChanged(join(outDir, 'version.c'), header + '/* This version is not set up. */\n');
}
writeIfChanged(join(ROOT, 'generated', 'versions.c'), header + '#include "game.h"\n\n' +
  VERSIONS.filter((v) => built.has(v.id)).map((v) => `extern const GameVersion game_version_${v.id};`).join('\n') +
  `\n\nconst GameVersion *const game_versions[GAME_VERSION_COUNT] = {\n` +
  VERSIONS.map((v) => `    ${built.has(v.id) ? `&game_version_${v.id}` : 'NULL'},`).join('\n') + '\n};\n');
