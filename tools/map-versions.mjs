// Usage: node tools/map-versions.mjs
// Finds the runtime's hook addresses (config/addresses.json, config/patches.json) in every
// version set up in local.json and saves them in config/version-addresses.json (addresses
// only, no bytes of any game). Needs the USA ROM, which the addresses are written for.
// Run it after adding or changing an address.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadRoms } from './lib/rom.mjs';
import { ADDRESSES, PATCHES, USA_ADDRESSES, mapAddresses, remapConfig } from './lib/versions.mjs';

const roms = loadRoms();
const usa = roms.find((r) => r.version.id === 'us');
if (!usa) { console.error('The Crusader of Centy (USA) ROM is needed: the addresses are found from it.'); process.exit(1); }
const out = { comment: 'Generated by tools/map-versions.mjs: config/addresses.json and config/patches.json for each other version. Do not edit.' };
for (const { version, rom } of roms) {
  if (version.id === 'us') continue;
  // Hook addresses must all be found; a patch that cannot be placed in this version is left
  // out of it (its feature is a little less complete there), with a warning.
  const map = mapAddresses(usa.rom, rom, USA_ADDRESSES, true);
  const hex = (a) => a.toString(16).toUpperCase().padStart(6, '0');
  const hooks = [...JSON.stringify(ADDRESSES).matchAll(/"([0-9A-F]{6})"/g)].map((x) => parseInt(x[1], 16));
  const lost = hooks.filter((a) => map.missing.includes(a));
  if (lost.length) { console.error(`${version.name}: hook addresses not found: ${lost.map(hex).join(', ')}`); process.exit(1); }
  const bare = (o) => JSON.parse(JSON.stringify(o, (k, v) => (k === 'comment' ? undefined : v)));
  const patches = bare(PATCHES);
  for (const a of map.missing) {
    for (const group of Object.values(patches)) if (group && typeof group === 'object') delete group[hex(a)];
  }
  out[version.id] = { addresses: bare(remapConfig(ADDRESSES, map)), patches: remapConfig(patches, map) };
  console.log(`${version.name}: ${USA_ADDRESSES.length - map.missing.length} of ${USA_ADDRESSES.length} addresses found` +
              (map.missing.length ? ` (patches left out: ${map.missing.map(hex).join(', ')})` : ''));
}
writeFileSync(join(ROOT, 'config', 'version-addresses.json'), JSON.stringify(out, null, 2) + '\n');
