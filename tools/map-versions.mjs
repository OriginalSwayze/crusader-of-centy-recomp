// Usage: node tools/map-versions.mjs
// Finds the runtime's hook addresses (config/addresses.json, config/patches.json) in every
// version set up in local.json and saves them in config/version-addresses.json (addresses
// only, no bytes of any game). Needs the USA ROM, which the addresses are written for.
// Run it after adding or changing an address.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadRoms } from './lib/rom.mjs';
import { ADDRESSES, PATCHES, USA_ADDRESSES, mapAddresses, remapConfig } from './lib/versions.mjs';

const roms = loadRoms();
const usa = roms.find((r) => r.version.id === 'us');
if (!usa) { console.error('The Crusader of Centy (USA) ROM is needed: the addresses are found from it.'); process.exit(1); }
const out = { comment: 'Generated by tools/map-versions.mjs: config/addresses.json and config/patches.json for each other version. Do not edit.' };
for (const { version, rom } of roms) {
  if (version.id === 'us') continue;
  const map = mapAddresses(usa.rom, rom);
  const bare = (o) => JSON.parse(JSON.stringify(o, (k, v) => (k === 'comment' ? undefined : v)));
  out[version.id] = { addresses: bare(remapConfig(ADDRESSES, map)), patches: bare(remapConfig(PATCHES, map)) };
  console.log(`${version.name}: ${USA_ADDRESSES.length} addresses found`);
}
writeFileSync(join(ROOT, 'config', 'version-addresses.json'), JSON.stringify(out, null, 2) + '\n');
